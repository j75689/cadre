export type IconName = keyof typeof shapes;

// Icon is 16 px with a 1.5 px stroke. It is decoration (aria-hidden) unless
// it stands alone with a label; an icon-only control labels the control.
export function Icon({ name, size = 16, label, className }: { name: IconName; size?: number; label?: string; className?: string }) {
  return (
    <svg
      className={className ? `icon ${className}` : "icon"}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={(1.5 * 24) / size}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={label ? undefined : true}
      role={label ? "img" : undefined}
      aria-label={label}
      focusable="false"
    >
      {shapes[name]}
    </svg>
  );
}
